using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using UnityEditor;
using UnityEngine;

/// <summary>
/// Tools → Cues → Coverage Report: what every follower ability, spell, trinket and ritual buff plays (CueLibrary),
/// and which cue sounds are missing or unused. Writes Claude/Cues/CueCoverage.md and logs a one-line summary.
/// Run it after adding content: anything listed as "inferred" gets a family sound from what it does at runtime;
/// give it an entry in CueLibrary / SpellCues if it deserves its own.
/// </summary>
public static class CueCoverageReport
{
    const string OutputPath = "Claude/Cues/CueCoverage.md";

    [MenuItem("Tools/Cues/Coverage Report")]
    public static void Run()
    {
        string report = Build(out int missing, out int inferred);
        Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
        File.WriteAllText(OutputPath, report);
        Debug.Log("Cue coverage: " + missing + " missing sound(s), " + inferred + " ability/abilities on inferred cues. See " + OutputPath);
    }

    public static string Build(out int missingCount, out int inferredCount)
    {
        Assembly game = typeof(Card).Assembly;
        StringBuilder sb = new StringBuilder();
        HashSet<string> used = new HashSet<string>();
        inferredCount = 0;

        sb.AppendLine("# Cue coverage");
        sb.AppendLine();
        sb.AppendLine("Generated by Tools → Cues → Coverage Report from `CueLibrary` / `SpellCues`. "
            + "Sounds: `Resources/Audio/SFX/Cues` (`Tools/Audio/build_cue_sounds.py`).");
        sb.AppendLine();

        // Followers
        sb.AppendLine("## Followers");
        sb.AppendLine();
        sb.AppendLine("| Follower | Text | Cue |");
        sb.AppendLine("|---|---|---|");
        foreach (Type type in Concrete(game, typeof(Follower)))
        {
            Follower follower = TryCreate(type) as Follower;
            if (follower == null)
                continue;

            string text = Flatten(follower.Text);
            bool turnEffects = Overrides(type, "DoStartOfMyTurnEffects") || Overrides(type, "DoEndOfMyTurnEffects")
                || Overrides(type, "DoStartOfEachTurnEffects") || Overrides(type, "DoEndOfEachTurnEffects");
            bool triggered = turnEffects || follower.InnateEffects.Any(e => !(e is StaticEffectDef));
            string cue;
            if (!triggered)
            {
                cue = "static or none: silent";
            }
            else if (CueLibrary.HasCardEntry(type.Name, out CueDef def))
            {
                cue = Describe(def);
                used.Add(def.Sound);
            }
            else
            {
                string byDef = null;
                foreach (FollowerEffect effect in follower.InnateEffects)
                {
                    if (CueLibrary.HasEffectDefEntry(effect.GetType().Name, out CueDef effectDef))
                    {
                        byDef = Describe(effectDef) + " (via " + effect.GetType().Name + ")";
                        used.Add(effectDef.Sound);
                    }
                }
                if (byDef != null)
                {
                    cue = byDef;
                }
                else
                {
                    cue = "inferred from its actions (silent if it never acts, e.g. a stat aura)";
                    inferredCount++;
                }
            }
            sb.AppendLine("| " + type.Name + " | " + text + " | " + cue + " |");
        }
        sb.AppendLine();

        // Spells
        sb.AppendLine("## Spells");
        sb.AppendLine();
        sb.AppendLine("| Spell | Cast sound | VFX | Projectile |");
        sb.AppendLine("|---|---|---|---|");
        foreach (Type type in Concrete(game, typeof(Spell)))
        {
            Spell spell = TryCreate(type) as Spell;
            if (spell == null)
                continue;

            SpellCueDef def = CueLibrary.ForSpell(spell);
            bool explicitEntry = CueLibrary.HasSpellEntry(type.Name, out _);
            bool ownVfx = Overrides(type, "GetPlayVfx");
            bool ownThrow = Overrides(type, "GetThrowStyle");
            string sound = def == null ? "silent" : string.IsNullOrEmpty(def.Sound) ? "(its own VFX sound)" : def.Sound + (explicitEntry ? "" : " (default)");
            if (def != null && !string.IsNullOrEmpty(def.Sound))
                used.Add(def.Sound);
            string vfx = ownVfx ? "own GetPlayVfx" : def?.Vfx != null ? "SpellCues" : "";
            string thrown = ownThrow ? "own GetThrowStyle" : def?.Projectile != null ? def.Projectile.StrokeFolder : "";
            sb.AppendLine("| " + type.Name + " | " + sound + " | " + vfx + " | " + thrown + " |");
        }
        sb.AppendLine();

        // Trinkets and ritual buffs
        sb.AppendLine("## Trinkets and ritual buffs");
        sb.AppendLine();
        sb.AppendLine("Played when the effect's icon flares (an action of its own, or `MarkTriggered`). Passive effects that never act stay silent.");
        sb.AppendLine();
        sb.AppendLine("| Effect | Sound |");
        sb.AppendLine("|---|---|");
        foreach (Type type in game.GetTypes().Where(t => typeof(StaticPlayerEffect).IsAssignableFrom(t) && !t.IsAbstract).OrderBy(t => t.Name))
        {
            bool known = CueLibrary.HasPlayerEffectEntry(type.Name, out string sound);
            if (known)
                used.Add(sound);
            sb.AppendLine("| " + type.Name + " | " + (known ? sound : "Boon (default)") + " |");
        }
        used.Add(CueLibrary.Boon);
        sb.AppendLine();

        // Sounds
        foreach (string id in CueLibrary.AllSoundIds())
            used.Add(id);
        foreach (string id in new[] { "ImpactWater", "ImpactFire", "ImpactBlood", "ImpactInk", "ImpactGold" })
            used.Add(id);
        used.Remove(null);
        used.Remove("");

        List<string> missing = used.Where(id => Resources.Load<AudioClip>(CuePlayer.Folder + id) == null).OrderBy(id => id).ToList();
        missingCount = missing.Count;
        HashSet<string> files = new HashSet<string>(Directory.GetFiles("Assets/Resources/" + CuePlayer.Folder, "*.wav")
            .Select(Path.GetFileNameWithoutExtension));
        List<string> unused = files.Where(f => !used.Contains(f) && !used.Contains(StripVariant(f))).OrderBy(f => f).ToList();

        sb.AppendLine("## Sounds");
        sb.AppendLine();
        sb.AppendLine("- Missing: " + (missing.Count == 0 ? "none" : string.Join(", ", missing)));
        sb.AppendLine("- Unused files: " + (unused.Count == 0 ? "none" : string.Join(", ", unused)));
        sb.AppendLine("- Referenced: " + used.Count);
        return sb.ToString();
    }

    static string Describe(CueDef def)
    {
        string text = def.Sound;
        if (def.Projectile != null)
            text += ", projectile " + (def.Projectile.StrokeFolder ?? def.Projectile.PrefabPath);
        if (def.Extra != null)
            text += ", extra VFX";
        return text;
    }

    static string StripVariant(string name)
    {
        int underscore = name.LastIndexOf('_');
        return underscore > 0 && int.TryParse(name.Substring(underscore + 1), out _) ? name.Substring(0, underscore) : name;
    }

    static IEnumerable<Type> Concrete(Assembly assembly, Type baseType)
    {
        return assembly.GetTypes()
            .Where(t => t != baseType && baseType.IsAssignableFrom(t) && !t.IsAbstract && t.GetConstructor(Type.EmptyTypes) != null)
            .OrderBy(t => t.Name);
    }

    static object TryCreate(Type type)
    {
        try
        {
            return Activator.CreateInstance(type);
        }
        catch
        {
            return null;
        }
    }

    static bool Overrides(Type type, string method)
    {
        MethodInfo info = type.GetMethod(method, BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance);
        return info != null && info.DeclaringType == type;
    }

    static string Flatten(string text)
    {
        return string.IsNullOrEmpty(text) ? "" : text.Replace("\n", " / ").Replace("|", "/");
    }
}
